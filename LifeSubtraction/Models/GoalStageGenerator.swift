    private static func forCustomTitle(_ title: String, category: GoalCategory) -> [String] {
        let text = title.lowercased()

        if text.contains("旅行") || text.contains("旅遊") || text.contains("出國") {
            return ["編輯目的地", "旅遊基金儲蓄", "置辦簽證", "規劃行程", "出發"]
        }
        if text.contains("書") || text.contains("閱讀") {
            return ["選一本書", "安排閱讀時間", "開始閱讀", "持續讀完", "寫下心得"]
        }
        if text.contains("學") {
            return ["了解學習目標", "選擇學習資源", "開始練習", "持續投入", "掌握技能"]
        }
        if text.contains("寫") || text.contains("文章") {
            return ["確定主題", "列大綱", "撰寫初稿", "修改潤飾", "完成發佈"]
        }

        return category.defaultStageTitles
    }
